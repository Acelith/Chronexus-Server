#!/usr/bin/env python3
"""Generate or verify the implemented OpenAPI subset and its TypeScript schemas."""
import argparse
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    for union in ("oneOf", "anyOf"):
        if union in schema:
            return " | ".join(ts(item) for item in schema[union])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(ts(dict(schema, type=item)) for item in kind)
    if kind == "array":
        return f"Array<{ts(schema['items'])}>"
    if kind == "object":
        required = set(schema.get("required", []))
        fields = [f"  {json.dumps(key)}{'' if key in required else '?'}: {ts(value)};"
                  for key, value in schema.get("properties", {}).items()]
        if schema.get("additionalProperties") not in (None, False):
            raise ValueError("Map schemas need an explicit generator extension")
        return "{\n" + "\n".join(fields) + "\n}"
    return {"string": "string", "integer": "number", "number": "number",
            "boolean": "boolean", "null": "null"}[kind]


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    raw = subprocess.check_output(["cargo", "run", "--locked", "--quiet", "--", "openapi"], cwd=ROOT)
    schema = json.loads(raw)
    spec = json.dumps(schema, indent=2, sort_keys=True) + "\n"
    types = "// Generated by scripts/contract.py from the implemented OpenAPI. Do not edit.\n"
    types += "// Generated implemented API schemas; see docs/API.md for compatibility boundaries.\n\n"
    for name, item in sorted(schema["components"]["schemas"].items()):
        types += f"export type {name} = {ts(item)};\n\n"
    for name, content in [("api/openapi.json", spec), ("api/types.ts", types.rstrip() + "\n")]:
        target = ROOT / name
        if args.check:
            if not target.exists() or target.read_text() != content:
                raise SystemExit(f"Contract drift in {name}; run python3 scripts/contract.py")
        else:
            target.write_text(content)
    print("Contract and TypeScript schemas match." if args.check else "Generated contract and TypeScript schemas.")


if __name__ == "__main__":
    main()
